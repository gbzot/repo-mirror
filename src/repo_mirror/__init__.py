import click
import json
from collections import deque

#Command functions

@click.version_option(version="0.1.0")
@click.group()
def main() -> None:
    """Repository Mirror Tool"""
    pass

@main.command()
def test() -> None:
    """Run a test command."""
    click.echo("Testing:")
    latest_event = get_latest_structlog_value('repo-mirror.log', 'commit_hash')
    print(f"The latest commit_hash is: {latest_event}")

@main.command()
def init() -> None:
    """Initializes the repo-mirror tool"""
    click.echo("init test")

@main.command()
def status() -> None:
    """Checks for the status of the service"""
    click.echo("status test")

@main.command()
def start() -> None:
    """Starts the service"""
    click.echo("start test")

@main.command()
def stop() -> None:
    """Stops the service"""
    click.echo("stop test")
#Utilities

def get_latest_structlog_value(log_file_path, target_key):
    with open(log_file_path, 'r') as file:
        # deque with maxlen=1 efficiently fast-forwards to the last line
        # without storing the rest of the file in memory
        try:
            last_line = deque(file, maxlen=1)[0]
        except IndexError:
            return None # File is empty

    # Parse the JSON string generated by structlog
    latest_entry = json.loads(last_line)

    # Extract your specific value
    return latest_entry.get(target_key)


